const LANG_KEY = "viktoria-lang";

function currentLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "ru") return saved;
  } catch (error) {
    /* storage can be unavailable */
  }
  return "ru";
}

function applyLanguage(lang) {
  const next = translations[lang] ? lang : "ru";
  const dict = translations[next];
  document.documentElement.lang = next;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value == null) return;
    el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = dict[el.dataset.i18nAria];
    if (value == null) return;
    el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-content]").forEach((el) => {
    const value = dict[el.dataset.i18nContent];
    if (value == null) return;
    el.setAttribute("content", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = dict[el.dataset.i18nAlt];
    if (value == null) return;
    el.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.setLang === next));
  });

  const menu = document.querySelector(".nav-toggle");
  if (menu && menu.getAttribute("aria-expanded") === "true") {
    menu.setAttribute("aria-label", dict["nav.close"]);
  }

  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (error) {
    /* ignore */
  }
}

function initLanguage() {
  applyLanguage(currentLang());
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.setLang));
  });
}

function t(key) {
  const lang = document.documentElement.lang === "en" ? "en" : "ru";
  return translations[lang][key] || "";
}

window.ViktoriaI18n = { initLanguage, applyLanguage, t };
